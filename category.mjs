// 연예/예능성 기사 (수집 단계 필터를 빠져나온 사진·인터뷰 기사) → 분류에서 '기타'로 격리
const ENT_HINT = /\[사진\]|\[포토\]|연예|예능|배우|가수|아이돌|개그|코미디|방송인|유튜버|드라마 ?출연|열애|결혼 ?발표|프러포즈|SNS ?화제|부코페|웃음|스타|팬미팅|화보/;

export function categorize(item) {
  const title = String(item.t || item.title || "");
  if (ENT_HINT.test(title)) return "기타";
  // ① 제목 키워드가 뚜렷하면 그것을 신뢰 (통신사 사진캡션 등 sid가 엉뚱한 경우 방지)
  for (const [cat, re] of RULES) if (re.test(title)) return cat;
  // ② 네이버 섹션코드
  const m = String(item.nlink || item.url || "").match(/[?&]sid=(\d+)/);
  if (m && SID_MAP[m[1]]) return SID_MAP[m[1]];
  // ③ 맥락(본문 앞부분)으로 마지막 추정
  const ctx = String(item.ctx || "");
  for (const [cat, re] of RULES) if (re.test(ctx)) return cat;
  return "기타";
}


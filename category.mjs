// 인물명 + 시당 조직명을 함께 본다. 제목에 있을 때만 —
// 본문까지 보면 전당대회·타 인사 행사 기사가 통째로 딸려온다(실측: 이성권 본문전용 43건 중 대부분 무관).
// 2026-08-13: 인물명만 보던 규칙이 「국민의힘 부산시당, 공공기관 이전 토론회」류 시당 활동 기사를
//   26일간 37건(하루 1.4건) 놓쳐 조직명을 추가했다. 양당이 한 제목에 같이 나온 사례는 0건.
// 2026-08-13(2차): 위원장 이름은 본문(요약)까지 본다 — 사용자 요청. 다른 방이 '부산'을 본문까지
//   훑는 것과 같은 기준. 조직명은 제목만(본문 조직명은 단순 인용이 많다).
const PARTY_CHIEF = [
  { topic: "민주당시당",   name: /박홍배/, org: /(?:더불어)?민주당\s?부산\s?시당/, emoji: "🔵", label: "민주당 부산시당" },
  { topic: "국민의힘시당", name: /이성권/, org: /(?:국민의힘|국힘)\s?부산\s?시당/, emoji: "🔴", label: "국민의힘 부산시당" },
];
/** 여야 시당위원장 방 판별. 해당 없으면 null. → { topic, emoji, label } */
export function partyChief(item) {
  const t = String(item.t || item.title || "");
  const body = String(item.ctx || "");
  // 제목 매치가 본문 매치보다 우선 — 제목이 「국민의힘 부산시당…」인데 본문에 박홍배가 스쳐
  // 민주당 방으로 새는 것을 막는다(배열 순서만으로는 앞쪽 당이 이긴다).
  for (const { topic, name, org, emoji, label } of PARTY_CHIEF)
    if (name.test(t) || org.test(t)) return { topic, emoji, label };
  for (const { topic, name, emoji, label } of PARTY_CHIEF)
    if (name.test(body)) return { topic, emoji, label };
  return null;
}

// ── 부산시의회 전용 방 ──
// 조직명 + 개별 의원 활동(제목에 '부산시의원')을 함께 담는다 — 의원 발언·간담회·연구단체도
// 시의회 동향의 일부(실측 25일: 조직명 148건 + 시의원 108건 ≈ 10건/일).
// 제목 매칭만 사용(본문 매칭은 시정 일반 기사가 통째로 딸려옴 — 본문전용 374건 대부분 무관).
const RE_COUNCIL = /부산시의회|부산광역시의회|부산광역시\s?시의회|부산\s시의회|부산시의원|부산\s시의원/;
/** 시의회 방 판별. 해당 없으면 null. → { topic, emoji, label } (partyChief와 동일 형태) */
export function councilNews(item) {
  const t = String(item.t || item.title || "");
  if (RE_COUNCIL.test(t)) return { topic: "시의회", emoji: "🏛", label: "부산시의회" };
  return null;
}

